export type DictKey = keyof typeof zh;
const dicts: Record<Lang, Record<string, any>> = { zh, en };

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: DictKey, vars?: Record<string, string | number>) => string }>({
  lang: 'zh',
  setLang: () => {},
  t: (k) => k,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>('zh');
  const t = (k: DictKey, vars?: Record<string, string | number>) => {
    let s: string = dicts[lang][k] ?? dicts.zh[k] ?? k;
    if (vars) for (const [key, v] of Object.entries(vars)) s = s.replace(`{${key}}`, String(v));
    return s;
  };
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  return useContext(LangCtx);
}
